import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { chromium } = require('C:/Users/Matt/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const qa = path.join(root,'research','qa');
fs.mkdirSync(qa,{recursive:true});
const browser = await chromium.launch({headless:true,executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe'});
const page = await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];
page.on('pageerror',e=>errors.push(String(e)));
await page.goto(pathToFileURL(path.join(root,'Mordor Remastered Design Document.html')).href);
await page.screenshot({path:path.join(qa,'document-opening.png')});
await page.locator('#section-26').scrollIntoViewIfNeeded();
await page.screenshot({path:path.join(qa,'document-appendix.png')});
await page.getByRole('heading',{name:'12.6 Class restriction and alignment decision table',exact:true}).scrollIntoViewIfNeeded();
await page.screenshot({path:path.join(qa,'document-item-rules.png')});
await page.getByRole('heading',{name:'26.11 Second-pass item and importer audit',exact:true}).scrollIntoViewIfNeeded();
await page.screenshot({path:path.join(qa,'document-second-pass-data.png')});
await page.getByRole('heading',{name:'26.12 Supplied original-file findings — October 9, 2026',exact:true}).scrollIntoViewIfNeeded();
await page.screenshot({path:path.join(qa,'document-local-original.png')});
await page.getByRole('heading',{name:'6.6 Source-derived HP advancement algorithm',exact:true}).scrollIntoViewIfNeeded();
await page.screenshot({path:path.join(qa,'document-hp-rules.png')});
const desktop=await page.evaluate(()=>({sections:document.querySelectorAll('h2[id]').length,tables:document.querySelectorAll('table').length,horizontalOverflow:document.documentElement.scrollWidth>innerWidth,title:document.title}));
await page.setViewportSize({width:800,height:900});
await page.evaluate(()=>window.scrollTo(0,0));
await page.screenshot({path:path.join(qa,'document-narrow.png')});
const narrow=await page.evaluate(()=>({horizontalOverflow:document.documentElement.scrollWidth>innerWidth}));
const links=await page.locator('a').evaluateAll(nodes=>nodes.map(n=>n.getAttribute('href')));
const missing=[];
for(const href of links){
 if(!href || /^(https?:|#|mailto:)/.test(href)) continue;
 if(!fs.existsSync(path.resolve(root,decodeURIComponent(href))))missing.push(href);
}
await browser.close();
const result={desktop,narrow,pageErrors:errors,missingLocalLinks:missing};
fs.writeFileSync(path.join(qa,'document-check.json'),JSON.stringify(result,null,2));
console.log(JSON.stringify(result,null,2));
if(errors.length || missing.length || desktop.sections!==27 || desktop.horizontalOverflow || narrow.horizontalOverflow)process.exitCode=1;
